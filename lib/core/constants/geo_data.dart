/// Returns sorted countries list in the format expected by the UI.
List<Map<String, dynamic>> getCountries() {
  final list = kCountries
      .map((c) => <String, dynamic>{'code': c['code']!, 'name': c['name']!})
      .toList();
  list.sort((a, b) => (a['name'] as String).compareTo(b['name'] as String));
  return list;
}

/// Returns sorted cities for the given [countryCode].
List<Map<String, dynamic>> getCities(String countryCode) {
  final cities = List<String>.from(kCitiesByCountry[countryCode] ?? []);
  cities.sort();
  return cities.map((name) => <String, dynamic>{'name': name}).toList();
}
